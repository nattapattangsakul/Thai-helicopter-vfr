// Build script — produces every static file the PWA needs so it runs fully offline.
//   npm run build
// Outputs (committed, so GitHub Pages / any static host can serve the repo as-is):
//   vendor/   Leaflet + Lucide (no CDN at runtime)
//   fonts/    IBM Plex Sans Thai + IBM Plex Mono (thai + latin subsets, woff2)
//   css/app.css, css/fonts.css
//   icons/    PNG app icons generated from icons/icon.svg (+ maskable variant)
//   sw.js     precache manifest + version hash stamped in
import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const r = (...p) => path.join(ROOT, ...p);
const NM = r("node_modules");
const log = (...a) => console.log("•", ...a);
const mkdir = d => fs.mkdirSync(d, { recursive: true });
const copy = (a, b) => { mkdir(path.dirname(b)); fs.copyFileSync(a, b); };

// ---------- 1. vendor libraries ----------
copy(path.join(NM, "leaflet/dist/leaflet.js"), r("vendor/leaflet/leaflet.js"));
copy(path.join(NM, "leaflet/dist/leaflet.css"), r("vendor/leaflet/leaflet.css"));
for (const f of fs.readdirSync(path.join(NM, "leaflet/dist/images"))) copy(path.join(NM, "leaflet/dist/images", f), r("vendor/leaflet/images", f));
copy(path.join(NM, "lucide/dist/umd/lucide.min.js"), r("vendor/lucide.min.js"));
log("vendor copied");

// ---------- 2. self-hosted fonts ----------
fs.rmSync(r("fonts"), { recursive: true, force: true }); mkdir(r("fonts"));
let fontCss = "/* generated by scripts/build.mjs — IBM Plex (SIL OFL 1.1) via @fontsource */\n";
const FONT_SETS = [
  { pkg: "ibm-plex-sans-thai", weights: [400, 500, 600, 700], subsets: ["thai", "latin"] },
  { pkg: "ibm-plex-mono", weights: [400, 500, 600, 700], subsets: ["latin"] }
];
for (const set of FONT_SETS) for (const w of set.weights) {
  const css = fs.readFileSync(path.join(NM, "@fontsource", set.pkg, `${w}.css`), "utf8");
  for (const block of css.split(/(?=\/\* )/)) {
    const m = block.match(/\/\* (\S+) \*\//); if (!m) continue;
    if (!set.subsets.some(s => m[1] === `${set.pkg}-${s}-${w}-normal`)) continue;
    const file = `${m[1]}.woff2`;
    copy(path.join(NM, "@fontsource", set.pkg, "files", file), r("fonts", file));
    fontCss += block.replace(/src:[^;]+;/, `src: url(../fonts/${file}) format('woff2');`).trim() + "\n";
  }
}
fs.writeFileSync(r("css/fonts.css"), fontCss);
log("fonts:", fs.readdirSync(r("fonts")).length, "files");

// ---------- 3. Tailwind ----------
execSync(`npx tailwindcss -c tailwind.config.cjs -i css/app.src.css -o css/app.css --minify`, { cwd: ROOT, stdio: "inherit" });
log("css/app.css", (fs.statSync(r("css/app.css")).size / 1024).toFixed(1), "KB");

// ---------- 4. icons (rendered with the pre-installed Playwright Chromium) ----------
const ICONS = [
  ["icon-192.png", 192, false], ["icon-512.png", 512, false],
  ["maskable-192.png", 192, true], ["maskable-512.png", 512, true],
  ["apple-touch-icon.png", 180, true], ["favicon-32.png", 32, false]
];
const needIcons = process.argv.includes("--icons") || ICONS.some(([f]) => !fs.existsSync(r("icons", f)));
if (needIcons) {
  let pw; try { pw = await import("playwright"); } catch (_) { try { const { createRequire } = await import("node:module"); pw = createRequire(import.meta.url)("playwright"); } catch (e) { pw = null; } }
  if (!pw) console.warn("! playwright not found — icons not regenerated");
  else {
    const svg = fs.readFileSync(r("icons/icon.svg"), "utf8");
    const svgMask = fs.readFileSync(r("icons/icon-maskable.svg"), "utf8");
    const browser = await pw.chromium.launch();
    const page = await browser.newPage();
    for (const [file, size, mask] of ICONS) {
      await page.setViewportSize({ width: size, height: size });
      await page.setContent(`<html><body style="margin:0;background:transparent">${(mask ? svgMask : svg).replace("<svg ", `<svg width="${size}" height="${size}" `)}</body></html>`);
      await page.screenshot({ path: r("icons", file), omitBackground: !mask, clip: { x: 0, y: 0, width: size, height: size } });
    }
    await browser.close();
    log("icons rendered");
  }
}

// ---------- 5. service worker precache list + version ----------
const walk = d => fs.readdirSync(r(d), { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const PRECACHE = [
  "index.html", "manifest.webmanifest", "css/app.css", "css/fonts.css", "js/app.js",
  ...walk("vendor"), ...walk("fonts"), ...walk("icons").filter(f => /\.(png|svg)$/.test(f) && !f.includes("screenshot"))
].map(f => f.split(path.sep).join("/")).filter(f => !f.endsWith(".map"));
const hash = createHash("sha256");
for (const f of PRECACHE) {
  let buf = fs.readFileSync(r(f));
  if (f === "index.html") buf = Buffer.from(buf.toString("utf8").replace(/data-build="[^"]*"/, 'data-build=""'));
  hash.update(f).update(buf);
}
const swSrc = fs.readFileSync(r("scripts/sw.template.js"), "utf8");
const version = hash.digest("hex").slice(0, 10);
fs.writeFileSync(r("sw.js"), swSrc
  .replace("__VERSION__", version)
  .replace("__PRECACHE__", JSON.stringify(["./", ...PRECACHE.map(f => "./" + f)], null, 2)));
// stamp the version into the page so "about" can show it
const idx = fs.readFileSync(r("index.html"), "utf8").replace(/data-build="[^"]*"/, `data-build="${version}"`);
fs.writeFileSync(r("index.html"), idx);
log("sw.js version", version, "—", PRECACHE.length, "files precached");
